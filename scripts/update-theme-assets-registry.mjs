import fs from 'node:fs';

const registryPath = new URL('../src/data/gachaThemeAssets.generated.ts', import.meta.url);
const characters = [
  'mobirin', 'mobichi', 'yami', 'mobiyan', 'mobiyura', 'reomoby', 'potemoby', 'mobibou', 'babumoby',
  'magician', 'informant', 'tracker', 'safecracker', 'veiled-duchess', 'courier', 'commander',
];
const slots = [
  'appBackground', 'buttonPrimary', 'buttonSecondary', 'card', 'navigation', 'popup',
  'dressUpPopup', 'characterPickerPopup', 'reactionBookPopup',
  'iconButton', 'tab', 'closeButton', 'reselectButton',
  'dressUpButton', 'themeActionLabel', 'themeCharacterTab', 'themeResetButton',
];
const lines = [
  "import type { ImageSourcePropType } from 'react-native';",
  '',
  `export type GeneratedThemeAssetSlot = ${slots.map((slot) => `'${slot}'`).join(' | ')};`,
  'export type GeneratedThemeAssetGroup = Readonly<Record<GeneratedThemeAssetSlot, ImageSourcePropType>>;',
  '',
  '/** 16 characters × 5 styles. Generated by scripts/generate-theme-assets.ps1 and scripts/generate-theme-control-assets.ps1. */',
  'export const GENERATED_GACHA_THEME_ASSETS: Readonly<Record<string, GeneratedThemeAssetGroup>> = {',
];
for (const character of characters) {
  for (let style = 1; style <= 5; style += 1) {
    const styleDir = String(style).padStart(2, '0');
    lines.push(`  '${character}:${style}': {`);
    for (const slot of slots) {
      const extension = ['dressUpPopup', 'characterPickerPopup', 'reactionBookPopup'].includes(slot) ? 'jpg' : 'png';
      lines.push(`    ${slot}: require('../../assets/themes/${character}/${styleDir}/${slot}.${extension}'),`);
    }
    lines.push('  },');
  }
}
lines.push(
  '};',
  '',
  'export function getGeneratedGachaThemeAssets(characterId: string, styleNumber: number): GeneratedThemeAssetGroup {',
  '  const assets = GENERATED_GACHA_THEME_ASSETS[`${characterId}:${styleNumber}`];',
  '  if (!assets) throw new Error(`Missing generated theme assets for ${characterId}:${styleNumber}`);',
  '  return assets;',
  '}',
  '',
);
fs.writeFileSync(registryPath, lines.join('\n'));
console.log('Rebuilt generated theme asset registry with control slots.');
