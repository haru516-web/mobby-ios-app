function makeCharacterFurniture(characterId: MobbyId, sources: ImageSourcePropType[]): FurnitureAsset[] {
  return sources.map((source, index) => ({
    id: `${characterId}:furniture:${String(index + 1).padStart(2, '0')}` as FurnitureAssetId,
    characterId,
    label: `${CHARACTER_NAMES[characterId]}専用 ${String(index + 1).padStart(2, '0')}`,
    caption: 'このモビーだけの家具',
    source,
    emoji: '✦',
    placement: placementFor(index),
  }));
}

