function placementFor(index: number): FurnitureAsset['placement'] {
  const column = index % 5;
  const row = Math.floor(index / 5);
  const widths = [30, 32, 28, 34, 30];
  return {
    left: `${8 + column * 18}%` as `${number}%`,
    bottom: `${8 + (row % 3) * 14}%` as `${number}%`,
    width: `${widths[column]}%` as `${number}%`,
    zIndex: 4,
  };
}

